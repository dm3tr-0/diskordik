window.icon = function (name, size) {
    const paths = window.IconPaths[name];
    if (!paths) return '';
    const s = size || 20;
    return '<svg xmlns="http://www.w3.org/2000/svg" width="' + s + '" height="' + s + '" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">' + paths + '</svg>';
};

// Заполнить все [data-icon] элементы иконками при загрузке
window.applyIcons = function () {
    document.querySelectorAll('[data-icon]').forEach(function (el) {
        const name = el.getAttribute('data-icon');
        const size = el.getAttribute('data-size') || 20;
        el.innerHTML = window.icon(name, parseInt(size, 10));
    });
};
document.addEventListener('DOMContentLoaded', window.applyIcons);
